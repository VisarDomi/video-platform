"""An app registry: a folder with apps.json (and apps.local.json beside it, never in Git) that the
engine (this apps/ios: App/, Kit/, Extension/, scripts/) builds.

The public registry is apps/ios itself: the demo's apps and its plug-in (Providers/live). A
deployment keeps its own folder, e.g. private/apps/ios, with its apps, its provider plug-ins, its
keys and a link `engine` to this folder, and builds it with `--registry`:

    python3 engine/scripts/project.py --registry . some-app

apps.json:

    {"plugins": ["Providers/live"],                    # plug-in folders, relative to the registry
     "bundlePrefix": "com.example.videoplatform",      # with an app's bundleSuffix (or its bundleId)
     "pcServer": "https://localhost:29999", "pcAwayServer": "",
     "listNames": {"ts-live": "Wimbledon"},            # each download list's name (+/- button)
     "liveSites": {"ts-live": "https://localhost:28081"}, "phoneKeys": {},
     "localSuffix": "",                                # renewal name of a local app: key + this
     "apps": {"live-a-local": {"name": "...", "product": "...", "bundleSuffix": "...", "provider": "ts-live",
                               "native": "live", "live": true, "mediaKind": "hls", "build": "1",
                               "url": "...", "extensions": [], "webExtensions": {}, "keys": {}, "overrides": ""}}}

apps.local.json may set any top-level value (a deployment's addresses, prefix and phone keys).
An app with `overrides` names a folder with its own engine overrides and generator
(`project.py`, `build-provider.py`): a provider whose engine differs (original files).
"""
import json
from pathlib import Path

ENGINE = Path(__file__).resolve().parents[1]
SIMULATOR_ONLY = 'Checks.swift'  # simulator walk-throughs and fixtures, never in a phone build


class Registry:
    def __init__(self, folder=None):
        self.root = Path(folder).absolute() if folder else ENGINE
        data = json.loads((self.root / 'apps.json').read_text())
        local_file = self.root / 'apps.local.json'
        self.local_file = local_file if local_file.exists() else None
        local = json.loads(local_file.read_text()) if self.local_file else {}
        self.settings = {name: value for name, value in {**data, **local}.items() if name != 'apps'}
        self.apps = data['apps']

    def get(self, name, default=None): return self.settings.get(name, default)

    def plugins(self):
        return [self.root / folder for folder in self.get('plugins', [])]

    def plugin_manifests(self):
        return [(folder, json.loads((folder / 'plugin.json').read_text())) for folder in self.plugins()]

    def bundle_id(self, key):
        config = self.apps[key]
        return config.get('bundleId') or self.get('bundlePrefix', 'com.example.videoplatform') + '.' + config['bundleSuffix']

    def signing_name(self, key):
        return key if self.apps[key].get('native') else key + self.get('localSuffix', '')

    def sources(self, simulator):
        """Every app of a registry compiles the same sources (the engine and all its plug-ins), so
        the apps share compiled modules; Info.plist alone tells them apart."""
        files = sorted((ENGINE / 'App').glob('*.swift'))
        for folder in self.plugins(): files += sorted(folder.glob('*.swift'))
        return [path for path in files if simulator or not path.name.endswith(SIMULATOR_ONLY)]


def write_plugins(path, manifests):
    """Plugins.generated.swift: the site lists and simulator checks the plug-ins bring (their
    plugin.json), so the engine (NativeLists, AppDelegate) never names one."""
    lists = {name: kind for _, manifest in manifests for name, kind in manifest.get('lists', {}).items()}
    checks = {argument: kind for _, manifest in manifests for argument, kind in manifest.get('checks', {}).items()}
    lines = ['// Generated by scripts/project.py from the plug-ins\' plugin.json. Not in Git.', 'import UIKit', '',
             '@MainActor', 'enum Plugins {', '    static func list(_ name: String) -> NativeLists.Opened? {', '        switch name {']
    lines += [f'        case {json.dumps(name)}: return NativeLists.open({kind}.self)' for name, kind in sorted(lists.items())]
    lines += ['        default: return nil', '        }', '    }', '', '    #if targetEnvironment(simulator)',
              '    static func check(_ arguments: [String]) -> UIViewController? {']
    lines += [f'        if arguments.contains({json.dumps(argument)}) {{ return {kind}() }}' for argument, kind in sorted(checks.items())]
    lines += ['        return nil', '    }', '    #endif', '}', '']
    text = '\n'.join(lines)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text: path.write_text(text)
    return path
